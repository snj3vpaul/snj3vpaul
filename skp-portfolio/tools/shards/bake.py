"""Bake the hero fracture's shards: img/shards.webp + shards.js.

Run from skp-portfolio/:  python3 tools/shards/bake.py
Needs Python Playwright with Chromium, and Pillow. See bake.html for what it does.
"""
import base64, io, json, pathlib, subprocess, sys, time
from PIL import Image
from playwright.sync_api import sync_playwright

root = pathlib.Path(__file__).resolve().parents[2]
server = subprocess.Popen([sys.executable, '-m', 'http.server', '8833', '--directory', str(root)],
                          stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
try:
    time.sleep(.8)
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        page.goto('http://127.0.0.1:8833/tools/shards/bake.html')
        out = page.evaluate('bake()')
        browser.close()
finally:
    server.terminate()

png = base64.b64decode(out['png'].split(',', 1)[1])
Image.open(io.BytesIO(png)).save(root / 'img' / 'shards.webp', 'WEBP', lossless=True, method=6)
js = ('/* Generated by tools/shards/bake.py. Do not edit by hand: re-run the baker. */\n'
      'export const atlasUrl = new URL(\'./img/shards.webp\', import.meta.url);\n'
      f'export const map = {json.dumps(out["map"], separators=(",", ":"))};\n')
(root / 'shards.js').write_text(js)
print(f"{out['count']} shards; atlas {out['map']['atlas']}; "
      f"shards.webp {(root / 'img' / 'shards.webp').stat().st_size // 1024} KB; shards.js {len(js) // 1024} KB")
